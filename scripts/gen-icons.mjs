// Generates src/ui/icon-set.js from Phosphor Icons (duotone). Run: npm run icons
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'node_modules/@phosphor-icons/core/assets/duotone');
const MAP = {
  cam: 'camera', pearl: 'sparkle', smoked: 'fire-simple', crab: 'bug-beetle', crate: 'package', heart: 'heart', food: 'fork-knife', drop: 'drop',
  sun: 'sun', moon: 'moon-stars', rain: 'cloud-rain', coin: 'coins', wood: 'tree-evergreen', plastic: 'beer-bottle', fiber: 'plant', scrap: 'wrench',
  fish: 'fish', cooked: 'cooking-pot', water: 'drop-half', potato: 'carrot', melon: 'orange-slice', seed: 'grains', hook: 'anchor-simple',
  rod: 'flask', hammer: 'hammer', eat: 'fork-knife', tile: 'squares-four', fire: 'fire', plant: 'plant', net: 'grid-nine', lamp: 'lightbulb',
  gear: 'gear-six', pause: 'pause', bag: 'backpack', close: 'x', check: 'check', star: 'star', boat: 'sailboat', shark: 'warning', cat: 'cat',
  bed: 'bed', ladder: 'ladder-simple', up: 'arrow-fat-up', quest: 'flag-banner', trash: 'trash', house: 'house-line', compass: 'compass',
};
let out = '// GENERATED by scripts/gen-icons.mjs from @phosphor-icons/core (duotone). Do not edit by hand.\n';
out += 'const s = (b) => `<svg viewBox="0 0 256 256" aria-hidden="true" fill="currentColor">${b}</svg>`;\nexport const ICON = {\n';
for (const [k, n] of Object.entries(MAP)) {
  const f = path.join(dir, `${n}-duotone.svg`);
  if (!fs.existsSync(f)) throw new Error(`missing phosphor icon ${n}`);
  const body = fs.readFileSync(f, 'utf8').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  out += `  ${k}: s('${body.replace(/'/g, "\\'")}'),\n`;
}
out += '};\n';
fs.writeFileSync(path.join(root, 'src/ui/icon-set.js'), out);
console.log('wrote', Object.keys(MAP).length, 'icons');
